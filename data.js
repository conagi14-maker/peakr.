// デフォルト並び順を適用（開発者ページで設定した順番）
(function _applyCatDefaultOrder() {
  try {
    const order = JSON.parse(localStorage.getItem('trendy_cat_order_default') || '[]');
    if (!order.length) return;
    CATS_DATA.sort((a, b) => {
      if (a.id === 'all') return -1;
      if (b.id === 'all') return 1;
      const ia = order.indexOf(a.id);
      const ib = order.indexOf(b.id);
      if (ia < 0 && ib < 0) return 0;
      if (ia < 0) return 1;
      if (ib < 0) return -1;
      return ia - ib;
    });
  } catch(e) {}
})();

